/**
 * Report generation service.
 * Prepares data and invokes the browser print-to-PDF dialog.
 */
export const reportService = {
  /**
   * Triggers the native browser print dialog configured for forensic reports.
   */
  printReport() {
    window.print();
  },

  /**
   * Generates a downloadable plain text audit log.
   * @param {object} analysis 
   */
  downloadTextSummary(analysis) {
    if (!analysis) return;

    const content = `======================================================================
IMAGEFORENSICS AI — FORENSIC AUDIT SUMMARY REPORT
======================================================================
Analysis ID:         ${analysis.id}
Timestamp:           ${analysis.timestamp}
Processing Mode:     ${analysis.isDemo ? 'DEMO MODE (SYNTHETIC BENCHMARK)' : 'LIVE INFERENCE'}
Model Version:       ${analysis.modelVersion || 'ResNet18-FFT-DWT-v1.0'}
VERDICT STATE:        ${analysis.verdictState || analysis.verdict || 'Unavailable'}
MODEL AGREEMENT:      ${analysis.modelAgreement || 'Unavailable'}

FILE METADATA
----------------------------------------------------------------------
Filename:            ${analysis.metadata?.filename}
File Size:           ${analysis.metadata?.fileSize} bytes
MIME Type:           ${analysis.metadata?.mimeType}
SHA-256 Digest:      ${analysis.metadata?.sha256Digest}

PREDICTION & CONFIDENCE
----------------------------------------------------------------------
Classification:      ${analysis.verdict}
Confidence Score:    ${analysis.confidencePct}% (${analysis.scoreType})
RGB Spatial Score:   ${analysis.scores?.rgbBranch}%
FFT Frequency Score: ${analysis.scores?.fftBranch}%
Wavelet DWT Score:   ${analysis.scores?.dwtBranch}%

DIAGNOSTIC FINDINGS
----------------------------------------------------------------------
${(analysis.findings || []).map((f, i) => `${i + 1}. ${f}`).join('\n')}

MODEL COMPARISON
----------------------------------------------------------------------
${(analysis.models || []).map((model) => [
  `${model.name || model.key}: ${model.available ? (model.prediction || 'No prediction') : 'Model unavailable'}`,
  `  Real=${typeof model.real_probability === 'number' ? (model.real_probability * 100).toFixed(1) : 'N/A'}%`,
  `  Fake=${typeof model.fake_probability === 'number' ? (model.fake_probability * 100).toFixed(1) : 'N/A'}%`,
  `  Task=${model.task || 'N/A'}; Checkpoint=${model.model_version || 'N/A'}`,
].join('\n')).join('\n')}

RESEARCH & RESPONSIBLE USE DISCLAIMER
----------------------------------------------------------------------
${analysis.disclaimer}
Frequency-domain analysis provides probabilistic forensic indicators. It does
not constitute definitive proof of authenticity or manipulation. Results must
be corroborated across independent image provenance and metadata channels.
======================================================================
Generated by ImageForensics AI
`;

    const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `Forensic_Report_${analysis.id}.txt`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  },
};
